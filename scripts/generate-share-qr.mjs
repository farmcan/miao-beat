import fs from 'node:fs/promises';
import QRCode from 'qrcode';
const pkg=JSON.parse(await fs.readFile(new URL('../node_modules/qrcode/package.json',import.meta.url)));
if(pkg.version!=='1.5.4'||pkg.license!=='MIT')throw Error('Unreviewed QR generator');
const url='https://miao-beat.pages.dev/',code=QRCode.create(url,{errorCorrectionLevel:'M'});
const data={url,address:'miao-beat.pages.dev',size:code.modules.size,data:Array.from(code.modules.data)};
await fs.writeFile(new URL('../public/share-brand.js',import.meta.url),'// QR matrix generated by qrcode@1.5.4 (MIT); see vendor/qrcode-LICENSE.txt.\nexport const SHARE_BRAND='+JSON.stringify(data)+';\n');
const license=await fs.readFile(new URL('../node_modules/qrcode/license',import.meta.url),'utf8');
await fs.writeFile(new URL('../public/vendor/qrcode-LICENSE.txt',import.meta.url),license.trimEnd()+'\n');
